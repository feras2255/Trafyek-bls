-- 7) مساحات التخزين (Storage)
--    الأسماء مطابقة تماماً لما يستخدمه الكود.
-- =====================================================================
insert into storage.buckets (id, name, public)
values
  ('site-images', 'site-images', true),
  ('categories',  'categories',  true),
  ('products',    'products',    true),
  ('projects',    'projects',    true),
  ('partners',    'partners',    true),
  ('blogs',       'blogs',       true)
on conflict (id) do update set public = excluded.public;

-- قراءة عامة للصور + رفع/تعديل/حذف للمستخدم المسجّل فقط.
-- ملاحظة: إن ظهر خطأ "must be owner of table objects" فأنشئ نفس السياسات
--         يدوياً من: Storage > Policies في لوحة Supabase.
do $$
declare
  b text;
begin
  foreach b in array array[
    'site-images','categories','products','projects','partners','blogs'
  ] loop
    execute format('drop policy if exists %I on storage.objects', b || '_public_read');
    execute format(
      'create policy %I on storage.objects for select to anon, authenticated using (bucket_id = %L)',
      b || '_public_read', b
    );

    execute format('drop policy if exists %I on storage.objects', b || '_auth_insert');
    execute format(
      'create policy %I on storage.objects for insert to authenticated with check (bucket_id = %L)',
      b || '_auth_insert', b
    );

    execute format('drop policy if exists %I on storage.objects', b || '_auth_update');
    execute format(
      'create policy %I on storage.objects for update to authenticated using (bucket_id = %L) with check (bucket_id = %L)',
      b || '_auth_update', b, b
    );

    execute format('drop policy if exists %I on storage.objects', b || '_auth_delete');
    execute format(
      'create policy %I on storage.objects for delete to authenticated using (bucket_id = %L)',
      b || '_auth_delete', b
    );
  end loop;
end
$$;


