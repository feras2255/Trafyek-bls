-- 4.2 المفاتيح الأجنبية للتصنيفات
--     on delete restrict: لا يُحذف تصنيف مرتبط بمنتجات (الكود يعالج الخطأ 23503)
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'products_category_id_fkey'
  ) then
    alter table public.products
      add constraint products_category_id_fkey
      foreign key (category_id) references public.categories (id) on delete restrict;
  end if;

  if not exists (
    select 1 from pg_constraint where conname = 'projects_category_id_fkey'
  ) then
    alter table public.projects
      add constraint projects_category_id_fkey
      foreign key (category_id) references public.categories (id) on delete set null;
  end if;
end
$$;

