-- 4.4 مشغّلات updated_at
do $$
declare
  t text;
begin
  foreach t in array array[
    'site_settings','categories','products','projects','blogs','partners','pages'
  ] loop
    execute format('drop trigger if exists set_%s_updated_at on public.%I', t, t);
    execute format(
      'create trigger set_%s_updated_at before update on public.%I
       for each row execute function public.set_updated_at()', t, t
    );
  end loop;
end
$$;


-- =====================================================================
-- 5) ⚠️ الأمان: تفعيل RLS وضبط الصلاحيات
--    ------------------------------------------------------------------
--    قبل هذا القسم: أي زائر يملك مفتاح anon (وهو ظاهر في كود المتصفح)
--    يستطيع حذف وتعديل كل شيء، وقراءة كل رسائل التواصل.
--
--    بعده:
--      • الزائر (anon)        : قراءة المحتوى فقط + إرسال رسالة تواصل
--      • المسجّل (authenticated): صلاحية كاملة = لوحة التحكم
--      • service_role          : يتجاوز RLS دائماً (يُستخدم في الخادم فقط)
-- =====================================================================

alter table public.site_settings    enable row level security;
alter table public.categories       enable row level security;
alter table public.products         enable row level security;
alter table public.projects         enable row level security;
alter table public.blogs            enable row level security;
alter table public.partners         enable row level security;
alter table public.pages            enable row level security;
alter table public.contact_messages enable row level security;

-- إزالة أي سياسات مفتوحة قديمة على جداول المحتوى ثم إنشاء سياسات محكمة
do $$
declare
  t   text;
  pol record;
  content_tables text[] := array[
    'site_settings','categories','products','projects','blogs','partners','pages'
  ];
begin
  foreach t in array content_tables loop
    -- حذف كل السياسات السابقة على الجدول
    for pol in
      select policyname from pg_policies
      where schemaname = 'public' and tablename = t
    loop
      execute format('drop policy %I on public.%I', pol.policyname, t);
    end loop;

    -- قراءة عامة (الموقع يعرض هذا المحتوى للزوار)
    execute format(
      'create policy %I on public.%I for select to anon, authenticated using (true)',
      t || '_public_read', t
    );

    -- كتابة/تعديل/حذف للمستخدم المسجّل فقط (لوحة التحكم)
    execute format(
      'create policy %I on public.%I for insert to authenticated with check (true)',
      t || '_auth_insert', t
    );
    execute format(
      'create policy %I on public.%I for update to authenticated using (true) with check (true)',
      t || '_auth_update', t
    );
    execute format(
      'create policy %I on public.%I for delete to authenticated using (true)',
      t || '_auth_delete', t
    );
  end loop;
end
$$;

-- رسائل التواصل: الزائر يُرسل فقط ولا يقرأ شيئاً
do $$
declare
  pol record;
begin
  for pol in
    select policyname from pg_policies
    where schemaname = 'public' and tablename = 'contact_messages'
  loop
    execute format('drop policy %I on public.contact_messages', pol.policyname);
  end loop;
end
$$;

create policy contact_messages_public_insert
  on public.contact_messages for insert
  to anon, authenticated with check (true);

create policy contact_messages_auth_read
  on public.contact_messages for select
  to authenticated using (true);

create policy contact_messages_auth_update
  on public.contact_messages for update
  to authenticated using (true) with check (true);

create policy contact_messages_auth_delete
  on public.contact_messages for delete
  to authenticated using (true);


-- =====================================================================
-- 6) دالة إحصائيات لوحة التحكم
--    يستدعيها: supabase.rpc("get_dashboard_stats")
--    ترجع: { products, categories, projects, blogs, partners, messages }
-- =====================================================================
create or replace function public.get_dashboard_stats()
returns json
language sql
security definer
set search_path = public
stable
as $$
  select json_build_object(
    'products',   (select count(*) from public.products),
    'categories', (select count(*) from public.categories),
    'projects',   (select count(*) from public.projects),
    'blogs',      (select count(*) from public.blogs),
    'partners',   (select count(*) from public.partners),
    'messages',   (select count(*) from public.contact_messages)
  );
$$;

-- لا تُتاح للزوار: عدد الرسائل معلومة إدارية
revoke all on function public.get_dashboard_stats() from public, anon;
grant execute on function public.get_dashboard_stats() to authenticated;


